#!/bin/bash

set -euo pipefail

source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/base-test.sh"

require_command jq

test_tmp=$(mktemp -d)
trap 'rm -rf "$test_tmp"' EXIT

home_dir="$test_tmp/home"
stub_bin="$test_tmp/bin"
monitor_lua="$home_dir/.config/hypr/monitors.lua"
managed_lua="$home_dir/.config/hypr/hyprmoncfg-monitors.lua"
eval_out="$test_tmp/eval"
stderr_out="$test_tmp/stderr"
scale_log="$home_dir/.local/state/omarchy/monitor-scaling.log"
mkdir -p "$home_dir/.config/hypr" "$stub_bin"

cat >"$stub_bin/hyprctl" <<'SH'
#!/bin/bash
case "$1" in
  monitors)
    printf '%s\n' "$OMARCHY_TEST_MONITORS_JSON"
    ;;
  eval)
    printf '%s\n' "$2" >>"$OMARCHY_TEST_EVAL_OUT"
    exit "${OMARCHY_TEST_EVAL_STATUS:-0}"
    ;;
  *) exit 1 ;;
esac
SH
chmod +x "$stub_bin/hyprctl"

write_fixture() {
  cat >"$monitor_lua" <<'LUA'
local omarchy_gdk_scale = 1
local omarchy_monitor_scale = 1
hl.env("GDK_SCALE", tostring(omarchy_gdk_scale))
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = omarchy_monitor_scale })
LUA

  # hyprmoncfg owns this file and loads it after the user's monitors.lua.
  # No hyprmoncfg executable or daemon is needed for the persistence guard.
  cat >"$managed_lua" <<'LUA'
-- Generated by hyprmoncfg
hl.monitor({
  output = "desc:Example Display",
  mode = "2560x1440@144",
  position = "0x0",
  scale = 1,
})
LUA

  cat >"$home_dir/.config/hypr/hyprland.lua" <<'LUA'
local config = os.getenv("HOME") .. "/.config/hypr/"
dofile(config .. "monitors.lua")
dofile(config .. "hyprmoncfg-monitors.lua")
LUA

  monitor_json='[{"name":"DP-1","description":"Example Display","focused":true,"scale":1,"width":2560,"height":1440,"refreshRate":144,"x":0,"y":0,"transform":0}]'
  : >"$eval_out"
}

run_scaling() {
  HOME="$home_dir" \
    XDG_CONFIG_HOME="$home_dir/.config" \
    XDG_STATE_HOME="$home_dir/.local/state" \
    PATH="$stub_bin:$PATH" \
    OMARCHY_TEST_MONITORS_JSON="$monitor_json" \
    OMARCHY_TEST_EVAL_OUT="$eval_out" \
    "${OMARCHY_TEST_SCALING_COMMAND:-$ROOT/bin/omarchy-hyprland-monitor-scaling}" "$@" 2>"$stderr_out"
}

write_fixture
before=$(sha256sum "$monitor_lua")
managed_before=$(sha256sum "$managed_lua")
run_scaling up

grep -F 'scale = 1.25' "$eval_out" >/dev/null ||
  fail "scaling still applies to the focused output with a managed layout"
pass "scaling still applies to the focused output with a managed layout"

[[ $(sha256sum "$managed_lua") == "$managed_before" ]] ||
  fail "scaling does not rewrite another tool's generated configuration"
pass "scaling does not rewrite another tool's generated configuration"

# Writing the shared local triggers a full reload, which reloads the managed
# file's scale = 1 and undoes the runtime eval, even without a running daemon.
[[ $(sha256sum "$monitor_lua") == "$before" ]] ||
  fail "scaling does not persist a shared default overridden by a later included file" \
    "monitors.lua was rewritten even though hyprmoncfg-monitors.lua governs DP-1"
pass "scaling does not persist a shared default overridden by a later included file"

grep -F 'Not persisting scale:' "$stderr_out" >/dev/null ||
  fail "managed runtime-only scaling explains why it is not saved"
pass "managed runtime-only scaling explains why it is not saved"

# A pinned portrait display keeps its mode, position and transform. It must not
# jump to the compositor's automatically chosen edge when no reload follows.
write_fixture
monitor_json=$(jq -c '.[0] += {x: -1080, y: 640, transform: 3, refreshRate: 143.967}' <<<"$monitor_json")
run_scaling up
for field in 'position = "-1080x640"' 'transform = 3' 'mode = "2560x1440@143.967"'; do
  grep -F "$field" "$eval_out" >/dev/null || fail "runtime scaling preserves $field"
done
pass "runtime scaling preserves negative position, rotation and refresh rate"

# File presence is deliberately conservative: no arbitrary Lua imports are
# parsed or executed to decide whether another tool's file is currently loaded.
write_fixture
printf 'require("hypr.monitors")\n' >"$home_dir/.config/hypr/hyprland.lua"
before=$(sha256sum "$monitor_lua")
run_scaling up
[[ $(sha256sum "$monitor_lua") == "$before" ]] ||
  fail "a leftover nonempty managed file conservatively disables persistence"
pass "a leftover nonempty managed file conservatively disables persistence"

write_fixture
rm "$managed_lua"
run_scaling up
grep -Fx 'local omarchy_monitor_scale = 1.25' "$monitor_lua" >/dev/null ||
  fail "default scale persistence still works without a managed file"
pass "default scale persistence still works without a managed file"

write_fixture
: >"$managed_lua"
run_scaling up
grep -Fx 'local omarchy_monitor_scale = 1.25' "$monitor_lua" >/dev/null ||
  fail "an empty managed file does not disable default persistence"
pass "an empty managed file does not disable default persistence"

write_fixture
mv "$managed_lua" "$test_tmp/layout.lua"
ln -s "$test_tmp/layout.lua" "$managed_lua"
before=$(sha256sum "$monitor_lua")
managed_before=$(sha256sum "$test_tmp/layout.lua")
run_scaling up
[[ -L $managed_lua && $(sha256sum "$monitor_lua") == "$before" && $(sha256sum "$test_tmp/layout.lua") == "$managed_before" ]] ||
  fail "a symlinked managed layout and its target remain untouched"
pass "a symlinked managed layout and its target remain untouched"
rm "$managed_lua"

write_fixture
before=$(sha256sum "$monitor_lua")
[[ $(run_scaling) == 1 && ! -s $eval_out && $(sha256sum "$monitor_lua") == "$before" ]] ||
  fail "reading a managed display's scale does not change config or runtime state"
pass "reading a managed display's scale does not change config or runtime state"

# Every value interpolated into the Lua table must be a literal. Reject bad
# monitor data before invoking eval or touching persistence.
for field in name x y transform width height refreshRate; do
  write_fixture
  before=$(sha256sum "$monitor_lua")
  monitor_json=$(jq -c --arg field "$field" '.[0][$field] = "0\" }); os.execute(\"false\") --"' <<<"$monitor_json")
  if run_scaling up; then
    fail "unsafe monitor $field is rejected"
  fi
  [[ ! -s $eval_out && $(sha256sum "$monitor_lua") == "$before" ]] ||
    fail "unsafe monitor $field cannot reach Lua or config writes"
done
pass "unsafe connector names and geometry cannot reach Lua or config writes"

write_fixture
before=$(sha256sum "$monitor_lua")
audit_before=$(wc -l <"$scale_log")
if OMARCHY_TEST_EVAL_STATUS=1 run_scaling up; then
  fail "a failed compositor eval is reported"
fi
[[ $(sha256sum "$monitor_lua") == "$before" && $(wc -l <"$scale_log") == "$audit_before" ]] ||
  fail "a failed compositor eval is not persisted or audited as successful"
pass "a failed compositor eval is not persisted or audited as successful"
