#!/bin/bash

set -euo pipefail

source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/base-test.sh"

require_command jq

test_tmp=$(mktemp -d)
trap 'rm -rf "$test_tmp"' EXIT

home_dir="$test_tmp/home"
stub_bin="$test_tmp/bin"
monitor_lua="$home_dir/.config/hypr/monitors.lua"
managed_lua="$home_dir/.config/hypr/hyprmoncfg-monitors.lua"
eval_out="$test_tmp/eval"
mkdir -p "$home_dir/.config/hypr" "$stub_bin"

cat >"$monitor_lua" <<'LUA'
local omarchy_gdk_scale = 1
local omarchy_monitor_scale = 1
hl.env("GDK_SCALE", tostring(omarchy_gdk_scale))
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = omarchy_monitor_scale })
LUA

# hyprmoncfg owns this file, and loads it after the user's monitors.lua.
# This fixture needs no hyprmoncfg executable or daemon to reproduce the issue.
cat >"$managed_lua" <<'LUA'
-- Generated by hyprmoncfg
hl.monitor({
  output = "desc:Example Display",
  mode = "2560x1440@144",
  position = "0x0",
  scale = 1,
})
LUA

cat >"$home_dir/.config/hypr/hyprland.lua" <<'LUA'
local config = os.getenv("HOME") .. "/.config/hypr/"
dofile(config .. "monitors.lua")
dofile(config .. "hyprmoncfg-monitors.lua")
LUA

cat >"$stub_bin/hyprctl" <<'SH'
#!/bin/bash
case "$1" in
  monitors)
    printf '%s\n' '[{"name":"DP-1","description":"Example Display","focused":true,"scale":1,"width":2560,"height":1440,"refreshRate":144,"x":0,"y":0,"transform":0}]'
    ;;
  eval)
    printf '%s\n' "$2" >"$OMARCHY_TEST_EVAL_OUT"
    ;;
  *) exit 1 ;;
esac
SH
chmod +x "$stub_bin/hyprctl"

before=$(sha256sum "$monitor_lua")
managed_before=$(sha256sum "$managed_lua")
HOME="$home_dir" \
  XDG_CONFIG_HOME="$home_dir/.config" \
  XDG_STATE_HOME="$home_dir/.local/state" \
  PATH="$stub_bin:$PATH" \
  OMARCHY_TEST_EVAL_OUT="$eval_out" \
  "${OMARCHY_TEST_SCALING_COMMAND:-$ROOT/bin/omarchy-hyprland-monitor-scaling}" up

grep -F 'scale = 1.25' "$eval_out" >/dev/null ||
  fail "scaling still applies to the focused output with a managed layout"
pass "scaling still applies to the focused output with a managed layout"

[[ $(sha256sum "$managed_lua") == "$managed_before" ]] ||
  fail "scaling does not rewrite another tool's generated configuration"
pass "scaling does not rewrite another tool's generated configuration"

# The shared local is not authoritative here: writing it triggers a full config
# reload, which reloads the managed file's scale = 1 and undoes the runtime eval.
[[ $(sha256sum "$monitor_lua") == "$before" ]] ||
  fail "scaling does not persist a shared default overridden by a later included file" \
    "monitors.lua was rewritten even though hyprmoncfg-monitors.lua governs DP-1"
pass "scaling does not persist a shared default overridden by a later included file"
